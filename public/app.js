function openPaypalCheckout() {
  if (!state.cart.length) {
    setMessage(elements.orderMessage, t("cartRequired"), "error");
    return;
  }

  const subtotal = getSubtotal().toFixed(2);
  const orderDescription = state.cart
    .map((item) => {
      const product = state.products.find((entry) => entry.sku === item.sku);
      return `${item.quantity} x ${product?.name || item.sku}`;
    })
    .join(", ");

  const form = document.createElement("form");
  form.method = "post";
  form.action = "https://www.paypal.com/cgi-bin/webscr";
  form.target = "_blank";
  form.style.display = "none";

  const fields = {
    cmd: "_xclick",
    business: "info@zoi.ec",
    item_name: `ZOI PLUS order: ${orderDescription}`,
    amount: subtotal,
    currency_code: "USD",
    no_shipping: "2",
    custom: `zoi-plus-${Date.now()}`
  };

  Object.entries(fields).forEach(([name, value]) => {
    const input = document.createElement("input");
    input.type = "hidden";
    input.name = name;
    input.value = value;
    form.append(input);
  });

  document.body.append(form);
  form.submit();
  form.remove();
}

async function handleQuoteSubmit(event) {
  event.preventDefault();
  const quote = Object.fromEntries(new FormData(elements.quoteForm).entries());
  const hasPendingCustomItem = Boolean(
    quote.producto_buscado?.trim() ||
      quote.descripcion?.trim() ||
      quote.links_referencia?.trim() ||
      elements.quoteForm.querySelector('[name="fotos_referencia"]')?.files.length
  );
  if (hasPendingCustomItem && !addCustomQuoteItemFromForm()) return;
  if (!state.quoteItems.length && !state.customQuoteItems.length) {
    setMessage(elements.quoteMessage, t("quoteItemsRequired"), "error");
    return;
  }
  const catalogItems = state.quoteItems.map((item) => {
    const product = state.products.find((entry) => entry.sku === item.sku);
    return {
      type: "catalog",
      sku: item.sku,
      name: product?.name || item.sku,
      category: product?.category || "",
      quantity: item.quantity,
      description: product?.description || ""
    };
  });
  const customItems = state.customQuoteItems.map((item) => ({
    type: "custom",
    sku: "",
    name: item.name,
    category: "",
    quantity: item.quantity,
    description: item.description,
    estimated_budget: item.estimated_budget,
    photo_names: item.photo_names || [],
    reference_links: item.reference_links || item.references_or_photos || ""
  }));
  const items = [...catalogItems, ...customItems];
  const payload = {
    quote: {
      fecha_limite: quote.fecha_limite,
      pais_ciudad: quote.pais_ciudad,
      nombre: quote.nombre,
      whatsapp: quote.whatsapp,
      email: quote.email,
      notas: quote.notas
    },
    items,
    source: "zoi-plus-ecommerce",
    date: new Date().toISOString()
  };

  await submitJson("/api/quotes", payload, elements.quoteMessage, t("quoteSuccess"), t("quoteError"), () => {
    state.quoteItems = [];
    state.customQuoteItems = [];
    saveQuoteItems();
    saveCustomQuoteItems();
    renderQuoteList();
    renderCustomQuoteList();
    elements.quoteForm.reset();
  });
}

async function submitJson(url, payload, messageElement, successMessage, errorMessage, onSuccess) {
  setMessage(messageElement, "...", "");
  try {
    const response = await fetch(url, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(payload)
    });
    const data = await response.json();
    if (!response.ok || !data.ok) throw new Error(data.error || "Request failed");
    setMessage(messageElement, `${successMessage} ${data.id ? `#${data.id}` : ""}`, "success");
    onSuccess(data);
  } catch {
    setMessage(messageElement, errorMessage, "error");
  }
}

function setMessage(element, message, type) {
  element.className = `form-message ${type}`;
  element.textContent = message;
}

function getSubtotal() {
  return state.cart.reduce((total, item) => {
    const product = state.products.find((entry) => entry.sku === item.sku);
    return total + (product?.price || 0) * item.quantity;
  }, 0);
}

function saveCart() {
  localStorage.setItem(getCartStorageKey(), JSON.stringify(state.cart));
}

function loadCart() {
  try {
    const key = getCartStorageKey();
    const saved = localStorage.getItem(key);
    if (saved) return JSON.parse(saved);

    if (key === "zoi-cart:guest") {
      const legacyCart = localStorage.getItem("zoi-cart");
      if (legacyCart) {
        localStorage.setItem(key, legacyCart);
        localStorage.removeItem("zoi-cart");
        return JSON.parse(legacyCart);
      }
    }

    return [];
  } catch {
    return [];
  }
}

