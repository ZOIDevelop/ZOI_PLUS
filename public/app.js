function detectLanguage() {
  const saved = localStorage.getItem("zoi-language");
  if (saved === "en" || saved === "es") return saved;
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

function t(key, params = {}) {
  let text = translations[state.language][key] || translations.en[key] || key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replace(`{${name}}`, value);
  }
  return text;
}

function applyTranslations() {
  document.documentElement.lang = state.language;
  elements.languageToggle.textContent = state.language === "en" ? "ES" : "EN";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });

  document.title =
    state.language === "es"
      ? "ZOI PLUS | Compra o solicita cotización automática"
      : "ZOI PLUS | Shop or Request an Automatic Quote";

  renderFilters();
  renderProducts();
  renderCart();
  renderQuoteList();
  renderCustomQuoteList();
  renderAuth();
}

