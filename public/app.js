async function loadConfig() {
  try {
    const response = await fetch("/api/config");
    state.config = await response.json();
  } catch {
    state.config = {};
  }
  initGoogleSignIn();
}

function initGoogleSignIn() {
  if (state.config.googleClientId && !window.google?.accounts?.id) {
    setTimeout(initGoogleSignIn, 500);
    return;
  }

  if (!state.config.googleClientId || !window.google?.accounts?.id) {
    elements.googleSignInButton.hidden = true;
    elements.googleDevSignIn.hidden = Boolean(state.user);
    return;
  }

  window.google.accounts.id.initialize({
    client_id: state.config.googleClientId,
    callback: handleGoogleCredential
  });

  elements.googleSignInButton.hidden = Boolean(state.user);
  elements.googleDevSignIn.hidden = true;

  if (!state.user) {
    window.google.accounts.id.renderButton(elements.googleSignInButton, {
      type: "standard",
      theme: "outline",
      size: "medium",
      text: "signin_with",
      shape: "rectangular"
    });
  }
}

function handleGoogleCredential(response) {
  const payload = parseJwt(response.credential);
  signInUser({
    id: payload.sub,
    name: payload.name || payload.email || "Google",
    email: payload.email || "",
    picture: payload.picture || ""
  });
}

function signInUser(user) {
  const guestCart = [...state.cart];
  state.user = user;
  localStorage.setItem("zoi-user", JSON.stringify(user));
  state.cart = mergeCarts(loadCart(), guestCart);
  saveCart();
  renderAuth();
  renderCart();
}

function signOutUser() {
  state.user = null;
  localStorage.removeItem("zoi-user");
  state.cart = loadCart();
  renderAuth();
  renderCart();
  initGoogleSignIn();
}

function renderAuth() {
  const isSignedIn = Boolean(state.user);
  elements.userMenu.hidden = !isSignedIn;
  elements.googleSignInButton.hidden = isSignedIn || !state.config.googleClientId;
  elements.googleDevSignIn.hidden = isSignedIn || Boolean(state.config.googleClientId);

  if (!isSignedIn) return;

  elements.userName.textContent = state.user.name;
  elements.userName.title = t("signedInAs", { name: state.user.email || state.user.name });
  elements.userAvatar.textContent = (state.user.name || "G").trim().charAt(0).toUpperCase();
  if (state.user.picture) {
    elements.userAvatar.style.backgroundImage = `url("${state.user.picture}")`;
    elements.userAvatar.textContent = "";
  } else {
    elements.userAvatar.style.backgroundImage = "";
  }
}

async function loadProducts() {
  elements.catalogStatus.textContent = t("loading");
  try {
    const response = await fetch("/api/products");
    const data = await response.json();
    state.products = data.products || [];
    state.categories = data.categories || [];
    state.tags = data.tags || [];
    renderFilters();
    renderProducts();
    renderCart();
  } catch {
    elements.catalogStatus.textContent = "Could not load products.";
  }
}

function renderFilters() {
  fillSelect(elements.categoryFilter, t("allCategories"), state.categories);
  fillSelect(elements.tagFilter, t("allTags"), state.tags);
}

function fillSelect(select, label, values) {
  const current = select.value;
  select.innerHTML = "";
  const all = document.createElement("option");
  all.value = "";
  all.textContent = label;
  select.append(all);

  values.forEach((value) => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.append(option);
  });

  select.value = values.includes(current) ? current : "";
}

function renderProducts() {
  const query = elements.searchInput.value.trim().toLowerCase();
  const category = elements.categoryFilter.value;
  const tag = elements.tagFilter.value;
  const products = state.products.filter((product) => {
    const haystack = [product.name, product.category, product.description, product.sku, ...product.tags]
      .join(" ")
      .toLowerCase();
    return (!query || haystack.includes(query)) && (!category || product.category === category) && (!tag || product.tags.includes(tag));
  });

  const hasActiveSearch = Boolean(query || category || tag);
  const shouldLimit = !state.showAllProducts && !hasActiveSearch;
  const visibleProducts = shouldLimit ? products.slice(0, state.landingProductLimit) : products;

  elements.productGrid.innerHTML = "";
  elements.emptyState.hidden = products.length > 0;
  elements.catalogToggle.hidden = products.length <= state.landingProductLimit || hasActiveSearch;
  elements.catalogToggle.textContent = state.showAllProducts ? t("showFewerProducts") : t("viewAllProducts");
  elements.catalogStatus.textContent = shouldLimit
    ? t("productsFoundLimited", { shown: visibleProducts.length, count: products.length })
    : t("productsFound", { count: products.length });

  visibleProducts.forEach((product) => {
    const card = elements.productCardTemplate.content.firstElementChild.cloneNode(true);
    const image = card.querySelector("img");
    image.src = product.imageUrl;
    image.alt = product.name;
    image.addEventListener("error", () => image.classList.add("is-broken"));
    card.querySelector(".category").textContent = product.category;
    card.querySelector(".stock").textContent = t("inStock", { count: product.stock });
    card.querySelector("h3").textContent = product.name;
    const description = card.querySelector(".description");
    const descriptionToggle = card.querySelector(".description-toggle");
    description.textContent = product.description;
    descriptionToggle.textContent = t("readMore");
    descriptionToggle.addEventListener("click", () => {
      const isExpanded = card.classList.toggle("is-description-expanded");
      descriptionToggle.textContent = isExpanded ? t("readLess") : t("readMore");
    });
    card.querySelector(".price").textContent = product.price > 0 ? money(product.price) : t("priceOnRequest");

    const tagList = card.querySelector(".tag-list");
    product.tags.forEach((productTag) => {
      const chip = document.createElement("span");
      chip.className = "tag";
      chip.textContent = productTag;
      tagList.append(chip);
    });

    const sheetButton = card.querySelector(".technical-sheet-button");
    if (product.price <= 0) {
      sheetButton.hidden = false;
      sheetButton.textContent = t("technicalSheet");
      sheetButton.addEventListener("click", () => {
        const previousStatus = elements.catalogStatus.textContent;
        elements.catalogStatus.textContent = t("technicalSheetNote");
        window.setTimeout(() => {
          if (elements.catalogStatus.textContent === t("technicalSheetNote")) {
            elements.catalogStatus.textContent = previousStatus;
          }
        }, 3500);
      });
    }

    const button = card.querySelector(".product-actions .button");
    button.textContent = product.price > 0 ? t("addToCart") : t("quoteProduct");
    button.addEventListener("click", () => {
      if (product.price > 0) addToCart(product.sku);
      else addToQuote(product.sku);
    });
    elements.productGrid.append(card);
  });
}

function addToQuote(sku) {
  const product = state.products.find((item) => item.sku === sku);
  if (!product) return;
  const existing = state.quoteItems.find((item) => item.sku === sku);
  if (existing) existing.quantity += 1;
  else state.quoteItems.push({ sku, quantity: 1 });
  saveQuoteItems();
  renderQuoteList();
  setMessage(elements.quoteMessage, `${t("quoteAdded")}: ${product.name}`, "success");
  document.querySelector("#quote")?.scrollIntoView({ behavior: "smooth" });
}

function renderQuoteList() {
  elements.quoteList.innerHTML = "";
  const title = document.createElement("div");
  title.className = "quote-list-heading";
  title.innerHTML = `<strong>${t("quoteListTitle")}</strong>`;
  const clearButton = document.createElement("button");
  clearButton.type = "button";
  clearButton.className = "text-button";
  clearButton.textContent = t("clearQuoteList");
  clearButton.hidden = state.quoteItems.length === 0;
  clearButton.addEventListener("click", () => {
    state.quoteItems = [];
    saveQuoteItems();
    renderQuoteList();
  });
  title.append(clearButton);
  elements.quoteList.append(title);

  if (!state.quoteItems.length) {
    const empty = document.createElement("p");
    empty.className = "form-message";
    empty.textContent = t("quoteListEmpty");
    elements.quoteList.append(empty);
    return;
  }

  state.quoteItems.forEach((item) => {
    const product = state.products.find((entry) => entry.sku === item.sku) || { name: item.sku, category: "" };
    const row = document.createElement("div");
    row.className = "quote-item";
    row.innerHTML = `
      <div>
        <strong></strong>
        <span></span>
      </div>
      <div class="quantity-control">
        <button type="button" aria-label="Decrease">-</button>
        <output></output>
        <button type="button" aria-label="Increase">+</button>
      </div>
      <button class="remove-item" type="button" aria-label="Remove">x</button>
    `;
    row.querySelector("strong").textContent = product.name;
    row.querySelector("span").textContent = product.category;
    row.querySelector("output").textContent = item.quantity;
    row.querySelectorAll(".quantity-control button")[0].addEventListener("click", () => updateQuoteQuantity(item.sku, item.quantity - 1));
    row.querySelectorAll(".quantity-control button")[1].addEventListener("click", () => updateQuoteQuantity(item.sku, item.quantity + 1));
    row.querySelector(".remove-item").addEventListener("click", () => updateQuoteQuantity(item.sku, 0));
    elements.quoteList.append(row);
  });
}

function updateQuoteQuantity(sku, quantity) {
  const item = state.quoteItems.find((entry) => entry.sku === sku);
  if (!item) return;
  item.quantity = Math.max(0, quantity);
  state.quoteItems = state.quoteItems.filter((entry) => entry.quantity > 0);
  saveQuoteItems();
  renderQuoteList();
}

function addCustomQuoteItemFromForm() {
  const productInput = elements.quoteForm.querySelector('[name="producto_buscado"]');
  const descriptionInput = elements.quoteForm.querySelector('[name="descripcion"]');
  const quantityInput = elements.quoteForm.querySelector('[name="cantidad"]');
  const budgetInput = elements.quoteForm.querySelector('[name="presupuesto_estimado"]');
  const photosInput = elements.quoteForm.querySelector('[name="fotos_referencia"]');
  const linksInput = elements.quoteForm.querySelector('[name="links_referencia"]');
  const name = productInput.value.trim();
  const description = descriptionInput.value.trim();
  const photoNames = [...photosInput.files].map((file) => file.name);
  const referenceLinks = linksInput.value.trim();
  if (!name && !description && !photoNames.length && !referenceLinks) {
    setMessage(elements.quoteMessage, t("quoteItemsRequired"), "error");
    return false;
  }

  state.customQuoteItems.push({
    id: `custom-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    name: name || t("wantedProduct"),
    description,
    quantity: Math.max(1, Number(quantityInput.value) || 1),
    estimated_budget: budgetInput.value.trim(),
    photo_names: photoNames,
    reference_links: referenceLinks
  });

  productInput.value = "";
  descriptionInput.value = "";
  quantityInput.value = "";
  budgetInput.value = "";
  photosInput.value = "";
  linksInput.value = "";
  saveCustomQuoteItems();
  renderCustomQuoteList();
  setMessage(elements.quoteMessage, t("customItemAdded"), "success");
  return true;
}

